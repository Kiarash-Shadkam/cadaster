export interface TariffCalculationResult {
  recommendedFeeTomans: number;
  badviFeeTomans: number;      // مرحله بدوی (۶۰ درصد)
  tajdidFeeTomans: number;     // مرحله تجدیدنظر (۴۰ درصد)
  taxStampDutyTomans: number;  // تمبر مالیاتی علی‌الحساب ماده ۱۰۳ (۵ درصد)
  supportFundTomans: number;   // سهم صندوق حمایت وکلا (۲.۵ درصد)
  barShareTomans: number;      // سهم کانون وکلای دادگستری (۱ درصد)
  totalStatutoryDeductions: number; // جمع کل کسورات قانونی وکیل
  netAttorneyFeeTomans: number;     // خالص دریافتی وکیل
}

/**
 * محاسبه حق‌الوکاله قانونی طبق آیین‌نامه تعرفه حق‌الوکاله، حق‌المشاوره و هزینه سفر (مصوب ۱۳۹۹)
 * و ماده ۱۰۳ قانون مالیات‌های مستقیم:
 * 
 * دعاوی مالی:
 * - تا ۵۰ میلیون تومان (۵۰۰ میلیون ریال): ۸ درصد
 * - از ۵۰ تا ۲۰۰ میلیون تومان: ۷ درصد نسبت به مازاد
 * - از ۲۰۰ تا ۱ میلیارد تومان: ۵ درصد نسبت به مازاد
 * - از ۱ میلیارد تا ۳ میلیارد تومان: ۴ درصد نسبت به مازاد
 * - مازاد بر ۳ میلیارد تومان: ۳ درصد
 */
export function calculateBarTariff(claimAmountTomans: number, customAgreedFeeTomans?: number): TariffCalculationResult {
  let tariffTotal = 0;

  if (claimAmountTomans <= 50_000_000) {
    tariffTotal = claimAmountTomans * 0.08;
  } else if (claimAmountTomans <= 200_000_000) {
    tariffTotal = 50_000_000 * 0.08 + (claimAmountTomans - 50_000_000) * 0.07;
  } else if (claimAmountTomans <= 1_000_000_000) {
    tariffTotal = 50_000_000 * 0.08 + 150_000_000 * 0.07 + (claimAmountTomans - 200_000_000) * 0.05;
  } else if (claimAmountTomans <= 3_000_000_000) {
    tariffTotal =
      50_000_000 * 0.08 +
      150_000_000 * 0.07 +
      800_000_000 * 0.05 +
      (claimAmountTomans - 1_000_000_000) * 0.04;
  } else {
    tariffTotal =
      50_000_000 * 0.08 +
      150_000_000 * 0.07 +
      800_000_000 * 0.05 +
      2_000_000_000 * 0.04 +
      (claimAmountTomans - 3_000_000_000) * 0.03;
  }

  // اگر وکیل حق‌الوکاله توافقی ثبت کرده باشد، محاسبات تمبر بر مبنای مبلغ توافقی صورت می‌پذیرد
  const effectiveFee = customAgreedFeeTomans && customAgreedFeeTomans > 0 ? customAgreedFeeTomans : tariffTotal;

  // مرحله بدوی ۶۰٪ و تجدیدنظر ۴۰٪ طبق ماده ۳ آیین‌نامه
  const badviFee = Math.round(effectiveFee * 0.6);
  const tajdidFee = Math.round(effectiveFee * 0.4);

  // تمبر مالیاتی ماده ۱۰۳ ق.م.م: ۵٪ علی‌الحساب
  const taxStamp = Math.round(effectiveFee * 0.05);

  // سهم صندوق حمایت وکلا: ۲.۵٪ (ماده ۸ قانون تشکیل صندوق حمایت)
  const supportFund = Math.round(effectiveFee * 0.025);

  // سهم کانون وکلا: ۱٪
  const barShare = Math.round(effectiveFee * 0.01);

  const totalDeductions = taxStamp + supportFund + barShare;
  const netFee = effectiveFee - totalDeductions;

  return {
    recommendedFeeTomans: Math.round(tariffTotal),
    badviFeeTomans: badviFee,
    tajdidFeeTomans: tajdidFee,
    taxStampDutyTomans: taxStamp,
    supportFundTomans: supportFund,
    barShareTomans: barShare,
    totalStatutoryDeductions: totalDeductions,
    netAttorneyFeeTomans: netFee,
  };
}

