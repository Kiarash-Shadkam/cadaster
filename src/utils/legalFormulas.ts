/**
 * تبدیل رشته تاریخ شمسی مانند "1403/08/15" به سال، ماه، روز عددی
 */
export function parseShamsiDate(shamsiStr: string): { year: number; month: number; day: number } | null {
  if (!shamsiStr) return null;
  const cleaned = shamsiStr.replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)));
  const parts = cleaned.split(/[\/\-.]/).map((p) => parseInt(p.trim(), 10));
  if (parts.length >= 3 && !isNaN(parts[0]) && !isNaN(parts[1]) && !isNaN(parts[2])) {
    return { year: parts[0], month: parts[1], day: parts[2] };
  }
  return null;
}

/**
 * افزودن روز به تاریخ شمسی با احتساب ماه‌های ۳۱، ۳۰ و ۲۹ روزه تقویم جلالی
 */
export function addDaysToShamsi(year: number, month: number, day: number, daysToAdd: number): string {
  let y = year;
  let m = month;
  let d = day + daysToAdd;

  while (true) {
    const daysInMonth = m <= 6 ? 31 : m <= 11 ? 30 : 29;
    if (d <= daysInMonth) {
      break;
    }
    d -= daysInMonth;
    m += 1;
    if (m > 12) {
      m = 1;
      y += 1;
    }
  }

  const mm = m < 10 ? `0${m}` : `${m}`;
  const dd = d < 10 ? `0${d}` : `${d}`;
  return `${y}/${mm}/${dd}`;
}

/**
 * محاسبه موعد قانونی طبق ماده ۴۴۵ ق.آ.د.م:
 * «روز ابلاغ و روز اقدام جزء مدت محسوب نمی‌شود.»
 * یعنی اگر مهلت ۲۰ روز باشد و در تاریخ ۱۴۰۳/۰۸/۱۰ ابلاغ شود:
 * روز ۱۰ آبان = روز ابلاغ (محسوب نمی‌شود).
 * روز ۱۱ الی ۳۰ آبان = ۲۰ روز انقضا.
 * روز ۱ آذر = آخرین روز اقدام است (در عمل ۲۰ روز + ۱ روز بعد از ابلاغ = ۲۱ روز اضافه می‌شود).
 */
export function calculateProceduralDeadlineDate(sanaDate: string, daysType: number): string {
  const parsed = parseShamsiDate(sanaDate);
  if (!parsed) return sanaDate;

  // طبق رویه قضایی و ماده ۴۴۵، آخرین روز اقدام = روز ابلاغ + مدت قانونی + ۱ روز
  return addDaysToShamsi(parsed.year, parsed.month, parsed.day, daysType + 1);
}

/**
 * دریافت تاریخ امروز شمسی تقریبی
 */
export function getTodayShamsi(): string {
  try {
    const now = new Date();
    const formatter = new Intl.DateTimeFormat('fa-IR-u-ca-persian', {
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
    });
    const parts = formatter.format(now);
    // Convert to standard digits: e.g. "۱۴۰۳/۰۸/۱۵" -> "1403/08/15"
    return parts.replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)));
  } catch {
    return '1403/08/20';
  }
}

/**
 * محاسبه تفاضل دو تاریخ شمسی به روز (تخمین تقریبی قابل اتکا)
 */
export function diffShamsiDays(futureShamsi: string, currentShamsi: string): number {
  const pFuture = parseShamsiDate(futureShamsi);
  const pCurrent = parseShamsiDate(currentShamsi);
  if (!pFuture || !pCurrent) return 0;

  // Total day index approximation
  const toDayIndex = (y: number, m: number, d: number) => {
    let days = y * 365;
    for (let i = 1; i < m; i++) {
      days += i <= 6 ? 31 : i <= 11 ? 30 : 29;
    }
    days += d;
    return days;
  };

  return toDayIndex(pFuture.year, pFuture.month, pFuture.day) - toDayIndex(pCurrent.year, pCurrent.month, pCurrent.day);
}

export function getDeadlineUrgency(dueDateShamsi: string): {
  daysLeft: number;
  status: 'urgent' | 'warning' | 'normal' | 'expired';
  statusLabel: string;
} {
  const today = getTodayShamsi();
  const daysLeft = diffShamsiDays(dueDateShamsi, today);

  if (daysLeft < 0) {
    return { daysLeft, status: 'expired', statusLabel: 'مهلت منقضی گردیده است' };
  }
  if (daysLeft <= 3) {
    return { daysLeft, status: 'urgent', statusLabel: `${toPersianDigits(daysLeft)} روز مانده (فوری و حیاتی)` };
  }
  if (daysLeft <= 7) {
    return { daysLeft, status: 'warning', statusLabel: `${toPersianDigits(daysLeft)} روز مانده (نیازمند اقدام سریع)` };
  }
  return { daysLeft, status: 'normal', statusLabel: `${toPersianDigits(daysLeft)} روز تا انقضای موعد` };
}

